using Content.Shared._Moffstation.BladeServer;
using Content.Shared.Dataset;
using Robust.Shared.Prototypes;

namespace Content.Shared._Moffstation.Chitter;

/// This component is used to make entity tables of <see cref="ChitterServerEmagEffectPrototype"/>, and that's it.
[RegisterComponent]
public sealed partial class ChitterServerEmagEffectComponent : Component
{
    [DataField(required: true)] public ProtoId<ChitterServerEmagEffectPrototype> Effect;
}

/// The definition of an effect which can be applied to a <see cref="ChitterServerComponent"/> when it's emagged.
[Prototype]
public sealed partial class ChitterServerEmagEffectPrototype : IPrototype
{
    /// <inheritdoc/>
    [IdDataField]
    public string ID { get; private set; } = default!;

    /// When affected, the server's <see cref="BladeServerComponent.StripeColor"/> is changed to this.
    [DataField]
    public Color? ServerColor;

    /// When affected, all users on the chitter server have their avatars changed to one of these.
    [DataField]
    public List<ProtoId<ChitterAvatarPrototype>> Avatars = new();

    /// When affected, all users on the chitter server have their titles changed to this.
    [DataField]
    public LocId? JobTitle;

    /// When affected, all users on the chitter server have their names changed to a name generated by this.
    /// Names are created by concatenating a pick from each element in the list.
    [DataField]
    public List<ProtoId<LocalizedDatasetPrototype>> NameParts = new();
}
