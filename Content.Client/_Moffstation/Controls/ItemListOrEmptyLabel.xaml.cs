using System.Collections;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Moffstation.Controls;

/// <summary>
/// An <seealso cref="ItemList"/> with additional functionality.
/// Right now, all it does it show a label when there are no items in the list. Access the underlying item list through
/// <seealso cref="Items"/>, however operations which modify the contents of the list should be performed through the
/// functions defined on this type.
/// </summary>
/// <seealso cref="ItemList"/>
[GenerateTypedNameReferences, Virtual]
public partial class ItemListOrEmptyLabel : Control
{
    /// The text of the label displayed when this item list is empty.
    public string? EmptyText { get => NoItemsLabel.Text; set => NoItemsLabel.Text = value; }

    /// <inheritdoc cref="ItemList.SelectMode"/>
    public ItemList.ItemListSelectMode SelectMode { get => Items.SelectMode; set => Items.SelectMode = value; }

    public ItemListOrEmptyLabel()
    {
        RobustXamlLoader.Load(this);
    }

    private void UpdateVisibility()
    {
        if (Items.Count == 0)
        {
            Items.Visible = false;
            NoItemsLabel.Visible = true;
        }
        else
        {
            Items.Visible = true;
            NoItemsLabel.Visible = false;
        }
    }

    public void Add(IEnumerable<ItemList.Item> items)
    {
        Items.Add(items);
        UpdateVisibility();
    }

    public void Add(ItemList.Item item)
    {
        Items.Add(item);
        UpdateVisibility();
    }

    public void AddItems(
        IEnumerable<string> texts,
        Texture? icon = null,
        bool selectable = true,
        object? metadata = null,
        float iconScale = 1
    )
    {
        Items.AddItems(texts, icon, selectable, metadata, iconScale);
        UpdateVisibility();
    }

    public ItemList.Item AddItem(string text,
        Texture? icon = null,
        bool selectable = true,
        object? metadata = null,
        float iconScale = 1)
    {
        var ret = Items.AddItem(text, icon, selectable, metadata, iconScale);
        UpdateVisibility();
        return ret;
    }

    public void Clear()
    {
        Items.Clear();
        UpdateVisibility();
    }
}
