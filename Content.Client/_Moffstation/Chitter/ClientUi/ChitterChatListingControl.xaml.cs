using Content.Shared._Moffstation.Chitter;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Moffstation.Chitter.ClientUi;

[GenerateTypedNameReferences]
public sealed partial class ChitterChatListingControl : Control
{
    public event Action? OnNewChat;
    public event Action<ChitterChatId>? OnChatSelected;

    public ChitterChatListingControl()
    {
        RobustXamlLoader.Load(this);
        NewChatButton.OnPressed += _ => OnNewChat?.Invoke();
    }

    public void Update(bool connected, IEnumerable<ChitterUiChatEntry> chats, ChitterChatId? currentChat)
    {
        NewChatButton.Disabled = !connected;
        Items.RemoveAllChildren();
        foreach (var chat in chats)
        {
            Items.AddChild(
                ChitterChatListingItem.Create(
                    chat,
                    chat.Id == currentChat,
                    id => OnChatSelected?.Invoke(id)
                )
            );
        }
    }
}
