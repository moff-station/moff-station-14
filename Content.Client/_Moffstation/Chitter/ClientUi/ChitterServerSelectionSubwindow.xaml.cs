using System.Linq;
using Content.Shared._Moffstation.Chitter;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Moffstation.Chitter.ClientUi;

[GenerateTypedNameReferences]
public sealed partial class ChitterServerSelectionSubwindow : ChitterSubwindow
{
    public Action<NetEntity>? OnServerSelected;

    public ChitterServerSelectionSubwindow()
    {
        RobustXamlLoader.Load(this);

        ServerOptions.Items.OnItemSelected += _ => UpdateSubmitButton();
        ServerOptions.Items.OnItemDeselected += _ => UpdateSubmitButton();
        Submit.OnPressed += _ =>
        {
            if (ServerOptions.Items.GetSelected().TryFirstOrDefault(out var selected) &&
                selected.Metadata is NetEntity server)
            {
                OnServerSelected?.Invoke(server);
            }
        };
    }

    private void UpdateSubmitButton()
    {
        Submit.Disabled = !ServerOptions.Items.GetSelected().Any();
    }

    public void Update(IChitterUiData.ServerSelection state)
    {
        ServerOptions.Clear();
        foreach (var (name, server) in state.AvailableServers)
        {
            var item = ServerOptions.AddItem(name, metadata: server);
            if (server == state.CurrentServer)
                item.Selected = true;
        }
    }
}
