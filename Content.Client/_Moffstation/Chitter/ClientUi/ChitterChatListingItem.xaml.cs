using Content.Client._Moffstation.Extensions;
using Content.Shared._Moffstation.Chitter;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Moffstation.Chitter.ClientUi;

[GenerateTypedNameReferences]
public sealed partial class ChitterChatListingItem : ContainerButton
{
    private const string SelectedStyle = "PanelLight";
    private const string DefaultStyle = "PanelDeep";

    /// Whether or not this listing item is the currently selected item. Only affects visuals.
    public bool Selected
    {
        get;
        set
        {
            field = value;
            Panel.StyleClasses.Clear();
            Panel.StyleClasses.Add(value ? SelectedStyle : DefaultStyle);
        }
    }

    public ChitterChatListingItem()
    {
        RobustXamlLoader.Load(this);
    }

    public static ChitterChatListingItem Create(ChitterUiChatEntry chat, bool selected, Action<ChitterChatId> onPressed)
    {
        var ret = new ChitterChatListingItem();

        ret.Title.Text = chat.Title;
        ret.Preview.SetOrHideText(chat.Preview);
        ret.OnPressed += _ => onPressed(chat.Id);
        ret.Selected = selected;
        return ret;
    }
}
