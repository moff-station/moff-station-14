using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Moffstation.Chitter.ClientUi;

[GenerateTypedNameReferences]
public sealed partial class ChitterServerConnectionControl : BoxContainer
{
    public event Action? OnStartConnection;
    public event Action? OnDisconnect;

    public ChitterServerConnectionControl()
    {
        RobustXamlLoader.Load(this);

        ConnectButton.OnPressed += _ => OnStartConnection?.Invoke();
        DisconnectButton.OnPressed += _ => OnDisconnect?.Invoke();
    }

    public void Update((NetEntity, string)? connectedServer)
    {
        if (connectedServer is var (_, connectedServerName))
        {
            ConnectedToName.Text = connectedServerName;
            NoConnection.Visible = false;
            Connection.Visible = true;
        }
        else
        {
            NoConnection.Visible = true;
            Connection.Visible = false;
        }
    }
}
