using Content.Shared._Moffstation.Chitter;
using Content.Shared._Moffstation.Extensions;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Moffstation.Chitter.ClientUi;

[GenerateTypedNameReferences]
public sealed partial class ChitterClientControl : BoxContainer
{
    public ChitterClientControl() => RobustXamlLoader.Load(this);

    /// Wires up the events provided by this control (or its children) to send BUI messages through the given
    /// <paramref cref="predictedMsg"/> and <paramref name="nonPredictedMsg"/>.
    public void HandleEventsWithBuiMessages(Action<ChitterMsg> predictedMsg, Action<ChitterMsg> nonPredictedMsg)
    {
        UserControl.OnStartConnection += () => predictedMsg(new ChitterMsg.GoToServerSelection());
        UserControl.OnViewSettings += () => predictedMsg(new ChitterMsg.GoToSettings());
        ChatList.OnNewChat += () => predictedMsg(new ChitterMsg.GoToNewChat());
        ServerSelection.OnServerSelected += server => predictedMsg(new ChitterMsg.ChooseConnectedServer(server));
        UserControl.OnDisconnect += () => predictedMsg(new ChitterMsg.ChooseConnectedServer(null));
        Settings.OnSelectAvatar += avatar => predictedMsg(new ChitterMsg.SetOwnAvatar(avatar));
        NewChat.OnSubmit += (name, participants) => predictedMsg(new ChitterMsg.CreateNewChat(participants, name));
        ChatList.OnChatSelected += chat => predictedMsg(new ChitterMsg.ChangeSelectedChat(chat));
        CurrentChat.OnMessageEntered += (chat, content) => nonPredictedMsg(new ChitterMsg.SendMessage(chat, content));
        ServerSelection.OnClose += () => predictedMsg(new ChitterMsg.GoToMainView());
        Settings.OnClose += () => predictedMsg(new ChitterMsg.GoToMainView());
        NewChat.OnClose += () => predictedMsg(new ChitterMsg.GoToMainView());
    }

    public void Update(ChitterUiState state)
    {
        this.ServerSelection.Visible = false;
        Settings.Visible = false;
        NewChat.Visible = false;
        MainUi.Visible = true;

        _ = state.Data switch
        {
            IChitterUiData.NoIdentity noIdentity => NoIdentity(noIdentity),
            IChitterUiData.NoServer noServer => NoServer(noServer),
            IChitterUiData.Ok ok => Ok(ok),
            IChitterUiData.NewChat newChat => OnNewChat(newChat),
            IChitterUiData.ServerSelection serverSelection => ServerSelection(serverSelection),
            IChitterUiData.Settings settings => OnSettings(settings),
            _ => state.Data.ThrowUnknownInheritor<IChitterUiData, bool>(),
        };

        return;

        bool NoIdentity(IChitterUiData.NoIdentity _)
        {
            ChatList.Update(connected: false, chats: [], currentChat: null);
            UserControl.Update(hasIdentity: false, connectedServer: null);
            return true;
        }

        bool NoServer(IChitterUiData.NoServer noServer)
        {
            ChatList.Update(connected: false, chats: [], currentChat: null);
            CurrentChat.Update(null, noServer.Self.Id, _ => null);
            UserControl.Update(hasIdentity: true, connectedServer: null);
            return true;
        }

        bool Ok(IChitterUiData.Ok ok)
        {
            ChatList.Update(connected: true, ok.Chats, ok.CurrentChat?.Id);
            CurrentChat.Update(ok.CurrentChat, ok.Contacts.Self.Id, ok.Contacts.WithSelf().AsLookup());
            UserControl.Update(hasIdentity: true, ok.ConnectedServer);
            return true;
        }

        bool OnNewChat(IChitterUiData.NewChat newChat)
        {
            NewChat.Update(newChat.Contacts.WithoutSelf());
            NewChat.Visible = true;
            MainUi.Visible = false;
            return true;
        }

        bool ServerSelection(IChitterUiData.ServerSelection serverSelection)
        {
            this.ServerSelection.Update(serverSelection);
            this.ServerSelection.Visible = true;
            MainUi.Visible = false;
            return true;
        }

        bool OnSettings(IChitterUiData.Settings settings)
        {
            Settings.Update(settings.Self);
            Settings.Visible = true;
            MainUi.Visible = false;
            return true;
        }
    }
}
