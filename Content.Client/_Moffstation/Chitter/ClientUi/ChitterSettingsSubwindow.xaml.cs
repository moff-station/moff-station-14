using System.Linq;
using Content.Shared._Moffstation.Chitter;
using Content.Shared._Moffstation.Extensions;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._Moffstation.Chitter.ClientUi;

[GenerateTypedNameReferences]
public sealed partial class ChitterSettingsSubwindow : ChitterSubwindow
{
    private readonly ClientChitterClientSystem _clientSystem;
    private ProtoId<ChitterAvatarPrototype>? _selectedAvatar;

    public event Action<ProtoId<ChitterAvatarPrototype>>? OnSelectAvatar;

    public ChitterSettingsSubwindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.Resolve<EntityManager>().ResolveSystem(out _clientSystem);

        AvatarOptions.OnItemSelected += args =>
        {
            if (args.ItemList[args.ItemIndex].Metadata is ProtoId<ChitterAvatarPrototype> protoId &&
                _selectedAvatar != protoId)
            {
                _selectedAvatar = protoId;
                OnSelectAvatar?.Invoke(protoId);
            }
        };

        // In theory, these can get out of sync with the actual protos loaded, but dealing with that is a huge pain.
        foreach (var (proto, texture) in _clientSystem.GetSelectableAvatars())
        {
            AvatarOptions.AddItem(proto.ID, texture, metadata: new ProtoId<ChitterAvatarPrototype>(proto.ID));
        }
    }

    public void Update(ChitterAccount self)
    {
        NameValue.Text = self.Name;
        TitleValue.Text = self.JobTitle;
        self.ProfilePictureId.SetToOrHide(AvatarValue, _clientSystem);
        AvatarOptions.ClearSelected(
            except: AvatarOptions.Select(item => item.Metadata)
                .OfType<ProtoId<ChitterAvatarPrototype>>()
                .Index()
                .FirstOrNull(it => it.Item == self.ProfilePictureId)
                ?.Index
        );
    }
}
