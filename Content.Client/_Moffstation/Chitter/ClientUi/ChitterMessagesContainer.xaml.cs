using System.Numerics;
using Content.Shared._Moffstation.Chitter;
using Content.Shared._Moffstation.Extensions;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Moffstation.Chitter.ClientUi;

[GenerateTypedNameReferences]
public sealed partial class ChitterMessagesContainer : Control
{
    private static readonly Vector2 MaxScroll = new(int.MaxValue, int.MaxValue);

    private readonly ClientChitterClientSystem _chitter;
    private readonly HashSet<ChitterMessageId> _messages = new();

    public ChitterMessagesContainer()
    {
        RobustXamlLoader.Load(this);
        IoCManager.Resolve<EntityManager>().ResolveSystem(out _chitter);
    }

    public void Update(
        IEnumerable<ChitterUiMessage> messages,
        ChitterAccountId self,
        ChitterAccountLookup accountLookup
    )
    {
        foreach (var msg in messages)
        {
            if (_messages.Add(msg.Id))
            {
                Messages.AddChild(
                    ChitterMessageBubble.Create(
                        msg,
                        msg.Sender == self,
                        _chitter,
                        accountLookup
                    )
                );
            }
        }
    }

    public void Clear()
    {
        _messages.Clear();
        Messages.RemoveAllChildren();
    }

    public void SnapToBottomOfMessages() => Scroll.SetScrollValue(MaxScroll);
}
