using System.Linq;
using Content.Shared._Moffstation.Chitter;
using Content.Shared._Moffstation.Extensions;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Moffstation.Chitter.ClientUi;

[GenerateTypedNameReferences]
public sealed partial class ChitterNewChatSubwindow : ChitterSubwindow
{
    private readonly ClientChitterClientSystem _chitter;

    public event Action<string, IEnumerable<ChitterAccountId>>? OnSubmit;

    public ChitterNewChatSubwindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.Resolve<IEntityManager>().ResolveSystem(out _chitter);

        SubmitButton.OnPressed += _ =>
        {
            OnSubmit?.Invoke(ChatName.Text, SelectedAccounts());
            Clear();
        };
        Participants.Items.OnItemSelected += _ => SubmitButton.Disabled = !Participants.Items.GetSelected().Any();
    }

    public void Update(IEnumerable<ChitterAccount> candidateParticipants)
    {
        Participants.Clear();
        foreach (var account in candidateParticipants)
        {
            Participants.AddItem(
                Loc.GetString(
                    "chitter-client-contact-display",
                    ("name", account.Name),
                    ("title", account.JobTitle)
                ),
                _chitter.GetAvatarTexture(account.ProfilePictureId),
                selectable: true,
                metadata: account.Id
            );
        }
    }

    private IEnumerable<ChitterAccountId> SelectedAccounts() => Participants.Items.GetSelected()
        .Select(it => it.Metadata is ChitterAccountId id ? (ChitterAccountId?)id : null)
        .OfType<ChitterAccountId>();

    private void Clear()
    {
        ChatName.Text = "";
        foreach (var item in Participants.Items.GetSelected())
        {
            item.Selected = false;
        }
    }
}
