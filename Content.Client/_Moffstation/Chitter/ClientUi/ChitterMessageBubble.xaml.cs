using Content.Shared._Moffstation.Chitter;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Moffstation.Chitter.ClientUi;

[GenerateTypedNameReferences]
public sealed partial class ChitterMessageBubble : BoxContainer
{
    private static readonly Color OwnBgColor = Color.FromHex("#141F38");

    public ChitterMessageBubble()
    {
        RobustXamlLoader.Load(this);
    }

    public static ChitterMessageBubble Create(
        ChitterUiMessage message,
        bool isOwn,
        // Pass the chitter system in so that we don't need to resolve dependencies a billion times on UI refresh, etc.
        ClientChitterClientSystem chitter,
        ChitterAccountLookup accountLookup
    )
    {
        var ret = new ChitterMessageBubble();
        ret.MessageLabel.Text = message.Content;
        ret.TimestampLabel.Text = message.SentAt.ToString(@"%hh\:%mm\:%s");

        if (accountLookup(message.Sender) is { } sender)
        {
            ret.SenderLabel.Text = sender.Name;
            sender.ProfilePictureId.SetToOrHide(ret.AvatarTexture, chitter);
        }
        else
        {
            ret.SenderLabel.Text = Loc.GetString("chitter-client-unknown-sender");
        }

        if (isOwn)
        {
            ret.HorizontalAlignment = HAlignment.Right;
            ret.SenderRow.Visible = false;
            (ret.BubbleBackground.PanelOverride as StyleBoxFlat)?.BackgroundColor = OwnBgColor;
        }

        return ret;
    }
}
