using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Moffstation.Chitter.ClientUi;

[GenerateTypedNameReferences]
public sealed partial class ChitterUserControl : BoxContainer
{
    public event Action? OnStartConnection;
    public event Action? OnDisconnect;
    public event Action? OnViewSettings;

    public ChitterUserControl()
    {
        RobustXamlLoader.Load(this);
        Connection.OnStartConnection += () => OnStartConnection?.Invoke();
        Connection.OnDisconnect += () => OnDisconnect?.Invoke();
        ConfigurationButton.OnPressed += _ => OnViewSettings?.Invoke();
    }

    public void Update(bool hasIdentity, (NetEntity, string)? connectedServer)
    {
        if (!hasIdentity)
        {
            NoIdentity.Visible = true;
            Connection.Visible = false;
            ConfigurationButton.Disabled = true;
        }
        else
        {
            NoIdentity.Visible = false;
            Connection.Visible = true;
            ConfigurationButton.Disabled = false;
            Connection.Update(connectedServer);
        }
    }
}
