using Content.Shared._Moffstation.Chitter;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Moffstation.Chitter.ClientUi;

[GenerateTypedNameReferences]
public sealed partial class ChitterChatControl : Control
{
    [Dependency] private IUserInterfaceManager _uiMan = default!;

    private ChitterChatId? _currentChat;

    public event Action<ChitterChatId, string>? OnMessageEntered;

    public ChitterChatControl()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        Entry.OnTextEntered += args =>
        {
            if (_currentChat is { } c && args.Text != "")
            {
                OnMessageEntered?.Invoke(c, args.Text);
            }

            Entry.Clear();
        };
    }

    public void Update(ChitterUiChatDetail? chat, ChitterAccountId self, ChitterAccountLookup accountLookup)
    {
        if (_currentChat != chat?.Id)
        {
            Messages.Clear();
        }

        Messages.Update(chat?.Messages ?? [], self, accountLookup);
        _currentChat = chat?.Id;
        Entry.Editable = chat != null;

        if (_currentChat != chat?.Id)
        {
            Entry.Clear();
        }
    }
}
