using Content.Shared._Moffstation.Chitter;
using Content.Shared._Moffstation.Chitter.Probe;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Moffstation.Chitter.Probe;

[GenerateTypedNameReferences]
public sealed partial class ChitterProbeView : BoxContainer
{
    public event Action<ChitterChatId?>? OnChatSelected;

    public ChitterProbeView()
    {
        RobustXamlLoader.Load(this);

        LogControl.OnChatSelected += chat => OnChatSelected?.Invoke(chat);
    }

    public void UpdateState(ChitterProbeUiState state)
    {
        if (state.Data is { } data)
        {
            NoScanLabel.Visible = false;
            LogControl.Visible = true;
            LogControl.Update((data.ServerName, data.ScannedAt), data.SelectedChat, data.Chats, data.Accounts);
        }
        else
        {
            NoScanLabel.Visible = true;
            LogControl.Visible = false;
        }
    }
}
