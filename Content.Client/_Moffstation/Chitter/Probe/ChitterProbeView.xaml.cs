using Content.Shared._Moffstation.Chitter.Probe;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Moffstation.Chitter.Probe;

[GenerateTypedNameReferences]
public sealed partial class ChitterProbeView : BoxContainer
{
    public ChitterProbeView()
    {
        RobustXamlLoader.Load(this);
    }

    public void UpdateState(ChitterProbeUiState state)
    {
        if (state.Data is { } data)
        {
            NoScanLabel.Visible = false;
            ChatsContainer.Visible = true;
            LogContainer.Update(data.Chats, data.Accounts);
            HeaderLabel.Text = Loc.GetString("chitter-probe-last-scanned", ("server", data.ServerName));
        }
        else
        {
            NoScanLabel.Visible = true;
            ChatsContainer.Visible = false;
        }
    }
}
