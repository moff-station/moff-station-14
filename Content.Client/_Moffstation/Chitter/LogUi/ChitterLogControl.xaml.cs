using Content.Shared._Moffstation.Chitter;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Moffstation.Chitter.LogUi;

[GenerateTypedNameReferences]
public sealed partial class ChitterLogControl : BoxContainer
{
    private ChitterAccountLookup _accounts = _ => null;

    public bool Searchable
    {
        get;
        set
        {
            field = value;
            ChatListing.Searchable = value;
        }
    } = false;

    public event Action<ChitterChatId?>? OnChatSelected;

    public ChitterLogControl()
    {
        RobustXamlLoader.Load(this);

        ChatListing.OnChatSelected += chat => OnChatSelected?.Invoke(chat);
    }

    public void Update(
        (string, TimeSpan)? sourceNameAndCollectionTime,
        ChitterChatId? selectedChat,
        IReadOnlyCollection<ChitterUiChatDetail> chats,
        IEnumerable<ChitterAccount> accounts
    )
    {
        if (sourceNameAndCollectionTime is var (source, collectionTime))
        {
            HeaderLabel.Text =
                Loc.GetString("chitter-probe-last-scanned", ("server", source), ("time", collectionTime));
        }
        else
        {
            HeaderLabel.Visible = false;
        }

        _accounts = accounts.AsLookup();
        var infallibleChitterAccountLookup = _accounts.WithDefault(ChitterAccount.Unknown);
        ChatListing.Update(chats, _accounts, infallibleChitterAccountLookup);
        Messages.Update(chats.FirstOrNull(it => it.Id == selectedChat), infallibleChitterAccountLookup);
    }
}
