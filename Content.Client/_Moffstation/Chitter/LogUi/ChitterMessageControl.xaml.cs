using Content.Client._Moffstation.Chitter.ClientUi;
using Content.Shared._Moffstation.Chitter;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Moffstation.Chitter.LogUi;

[GenerateTypedNameReferences]
public sealed partial class ChitterMessageControl : BoxContainer
{
    public ChitterMessageControl()
    {
        RobustXamlLoader.Load(this);
    }

    public static ChitterMessageControl Create(ChitterUiMessage message, InfallibleChitterAccountLookup accountLookup)
    {
        var ret = new ChitterMessageControl();

        ret.Title.Text = Loc.GetString(
            "chitter-logs-message",
            ("time", message.SentAt.ToString(@"hh\:mm\:s")),
            ("name", accountLookup(message.Sender).Name),
            ("account", message.Sender.Display())
        );
        ret.Content.Text = message.Content;
        return ret;
    }
}
