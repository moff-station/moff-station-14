using System.Collections.Immutable;
using System.Linq;
using Content.Shared._Moffstation.Chitter;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Moffstation.Chitter.LogUi;

[GenerateTypedNameReferences]
public sealed partial class ChitterLogContainer : BoxContainer
{
    private ImmutableArray<ChitterUiChatDetail> _chats = [];
    private ChitterAccountLookup _accounts = _ => null;
    private InfallibleChitterAccountLookup _accountsOrUnknown = _ => ChitterAccount.Unknown;
    private ChitterChatId? _selected;

    public bool Searchable
    {
        get;
        set
        {
            field = value;
            SearchInput.Visible = value;
        }
    } = false;

    public ChitterLogContainer()
    {
        RobustXamlLoader.Load(this);
        SearchInput.OnTextChanged += _ => RebuildChatList();
    }

    private void SetAccounts(IEnumerable<ChitterAccount> accounts)
    {
        _accounts = accounts.AsLookup();
        _accountsOrUnknown = _accounts.WithDefault(ChitterAccount.Unknown);
    }

    public void Update(IEnumerable<ChitterUiChatDetail> chats, IEnumerable<ChitterAccount> accounts)
    {
        _chats = chats.ToImmutableArray();
        SetAccounts(accounts);
        RebuildChatList();
        RebuildMessageList();
    }

    private void RebuildChatList()
    {
        ChatList.RemoveAllChildren();

        foreach (var chat in ChatsFilteredBySearch().OrderByDescending(it => it.CreatedTime))
        {
            var names = string.Join(", ", chat.Participants.Select(it => _accountsOrUnknown(it).Name));
            var label = chat.Name.IsWhiteSpace() ? names : chat.Name;

            var button = new Button
            {
                Text = label,
                ToolTip = names,
                HorizontalExpand = true,
                ClipText = true,
                Pressed = chat.Id == _selected,
            };
            button.OnPressed += _ =>
            {
                _selected = chat.Id;
                RebuildChatList();
                RebuildMessageList();
            };
            ChatList.AddChild(button);
        }

        if (ChatList.ChildCount == 0)
        {
            NoChatsLabel.Visible = true;
            ChatList.Visible = false;
        }
        else
        {
            NoChatsLabel.Visible = false;
            ChatList.Visible = true;
        }
    }

    private void RebuildMessageList()
    {
        MessageList.RemoveAllChildren();

        if (_selected == null ||
            _chats.FirstOrNull(it => it.Id == _selected) is not { } chat ||
            chat.Messages.Length == 0)
        {
            NoMessagesLabel.Visible = true;
            MessagesContainer.Visible = false;
            return;
        }

        var names = string.Join(", ", chat.Participants.Select(it => _accountsOrUnknown(it).Name));
        DetailHeader.Text = chat.Name.IsWhiteSpace() ? names : chat.Name;

        foreach (var message in chat.Messages)
        {
            MessageList.AddChild(ChitterMessageControl.Create(message, _accountsOrUnknown));
        }

        NoMessagesLabel.Visible = false;
        MessagesContainer.Visible = true;
    }

    private IEnumerable<ChitterUiChatDetail> ChatsFilteredBySearch()
    {
        if (Searchable && SearchInput.Text.Trim() is var searchString && !searchString.IsWhiteSpace())
        {
            return _chats.Where(chat =>
                chat.Name.Contains(searchString, StringComparison.OrdinalIgnoreCase) ||
                chat.Participants.Any(participant =>
                    _accounts(participant)?.Name.Contains(searchString, StringComparison.OrdinalIgnoreCase) ??
                    false
                )
            );
        }

        return _chats;
    }
}
