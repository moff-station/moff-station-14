using Content.Shared._Moffstation.Chitter;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Moffstation.Chitter.LogUi;

[GenerateTypedNameReferences]
public sealed partial class ChitterLogMessagesContainer : Control
{
    public ChitterLogMessagesContainer()
    {
        RobustXamlLoader.Load(this);
    }

    public void Update(
        ChitterUiChatDetail? chat,
        InfallibleChitterAccountLookup accountsOrUnknown
    )
    {
        MessageList.RemoveAllChildren();

        if (chat is not { } c || c.Messages.Length == 0)
        {
            NoMessagesLabel.Visible = true;
            MessageList.Visible = false;
            return;
        }

        NoMessagesLabel.Visible = false;
        MessageList.Visible = true;
        foreach (var message in c.Messages)
        {
            MessageList.AddChild(ChitterMessageControl.Create(message, accountsOrUnknown));
        }
    }
}
