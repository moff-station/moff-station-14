using System.Collections.Immutable;
using System.Linq;
using Content.Shared._Moffstation.Chitter;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Moffstation.Chitter.LogUi;

[GenerateTypedNameReferences]
public sealed partial class ChitterLogChatListing : Control
{
    private ChitterAccountLookup _accounts = _ => null;
    private InfallibleChitterAccountLookup _accountsOrUnknown = _ => ChitterAccount.Unknown;
    private ImmutableArray<ChitterUiChatDetail> _allChats = [];

    public event Action<ChitterChatId?>? OnChatSelected;

    public bool Searchable
    {
        get;
        set
        {
            field = value;
            SearchInput.Visible = value;
        }
    } = false;

    public ChitterLogChatListing()
    {
        RobustXamlLoader.Load(this);

        SearchInput.OnTextChanged += _ => RebuildChatList();
        ChatList.Items.OnItemDeselected += _ => UpdateSelection();
        ChatList.Items.OnItemSelected += args => UpdateSelection();
    }

    public void Update(
        IEnumerable<ChitterUiChatDetail> chats,
        ChitterAccountLookup accounts,
        InfallibleChitterAccountLookup accountsOrUnknown
    )
    {
        _allChats = chats.ToImmutableArray();
        _accounts = accounts;
        _accountsOrUnknown = accountsOrUnknown;
        RebuildChatList();
    }

    private void UpdateSelection()
    {
        if (ChatList.Items.FirstOrDefault()?.Metadata is ChitterChatId chat)
        {
            OnChatSelected?.Invoke(chat);
            return;
        }

        OnChatSelected?.Invoke(null);
    }

    private void RebuildChatList()
    {
        ChatList.Clear();

        foreach (var chat in ChatsFilteredBySearch().OrderByDescending(it => it.CreatedTime))
        {
            var names = string.Join(", ", chat.Participants.Select(it => _accountsOrUnknown(it).Name));
            ChatList.AddItem(chat.Name.IsWhiteSpace() ? names : $"{chat.Name} ({names})", metadata: chat.Id);
        }
    }

    private IEnumerable<ChitterUiChatDetail> ChatsFilteredBySearch()
    {
        if (Searchable && SearchInput.Text.Trim() is var searchString && !searchString.IsWhiteSpace())
        {
            return _allChats.Where(chat =>
                chat.Name.Contains(searchString, StringComparison.OrdinalIgnoreCase) ||
                chat.Participants.Any(participant =>
                    _accounts(participant)?.Name.Contains(searchString, StringComparison.OrdinalIgnoreCase) ??
                    false
                )
            );
        }

        return _allChats;
    }
}
