using System.Linq;
using Content.Shared._Moffstation.Chitter;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._Moffstation.Chitter;

[GenerateTypedNameReferences]
public sealed partial class ChitterLogWindow : DefaultWindow
{
    private List<ChitterLogChat> _chats = [];
    private ChitterLogChat? _selected;

    public ChitterLogWindow()
    {
        RobustXamlLoader.Load(this);
        SearchInput.OnTextChanged += _ => RebuildChatList();
    }

    public void UpdateState(ChitterLogEuiState state)
    {
        _chats = state.Chats;

        // Keep the current selection (refreshed with new data) if it's still around.
        if (_selected != null)
            _selected = _chats.FirstOrDefault(c => c.ChatId == _selected.ChatId);

        RebuildChatList();
        RebuildMessageList();
    }

    private void RebuildChatList()
    {
        ChatList.RemoveAllChildren();

        var search = SearchInput.Text.Trim();
        var filtered = string.IsNullOrEmpty(search)
            ? _chats.AsEnumerable()
            : _chats.Where(c =>
                c.ChatName.Contains(search, StringComparison.OrdinalIgnoreCase) ||
                c.Participants.Any(p => p.Name.Contains(search, StringComparison.OrdinalIgnoreCase)));

        foreach (var chat in filtered.OrderByDescending(c => c.CreatedTime))
        {
            var names = string.Join(", ", chat.Participants.Select(p => p.Name));
            var label = string.IsNullOrWhiteSpace(chat.ChatName) ? names : chat.ChatName;
            if (chat.Archived)
                label = $"[{Loc.GetString("chitter-log-archived")}] {label}";

            var button = new Button
            {
                Text = label,
                ToolTip = names,
                HorizontalExpand = true,
                ClipText = true,
                Pressed = chat == _selected,
            };
            button.OnPressed += _ =>
            {
                _selected = chat;
                RebuildChatList();
                RebuildMessageList();
            };
            ChatList.AddChild(button);
        }

        if (ChatList.ChildCount == 0)
        {
            ChatList.AddChild(new Label
            {
                Text = Loc.GetString("chitter-log-no-chats"),
                FontColorOverride = Color.Gray,
            });
        }
    }

    private void RebuildMessageList()
    {
        MessageList.RemoveAllChildren();

        if (_selected == null)
        {
            DetailHeader.Text = Loc.GetString("chitter-log-select-chat");
            return;
        }

        var participantNames = string.Join(", ", _selected.Participants.Select(p => $"{p.Name} (#{p.AccountId:D4})"));
        DetailHeader.Text = string.IsNullOrWhiteSpace(_selected.ChatName)
            ? participantNames
            : $"{_selected.ChatName} — {participantNames}";

        foreach (var message in _selected.Messages)
        {
            var time = TimeSpan.FromSeconds(Math.Truncate(message.Timestamp.TotalSeconds)).ToString();
            var failedSuffix = message.DeliveryFailed ? $" ({Loc.GetString("chitter-log-delivery-failed")})" : "";

            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                Margin = new Thickness(0, 0, 0, 4),
            };

            row.AddChild(new Label
            {
                Text = $"[{time}] {message.SenderName} (#{message.SenderAccountId:D4}){failedSuffix}",
                FontColorOverride = Color.Gray,
            });
            row.AddChild(new Label
            {
                Text = message.Content,
            });

            MessageList.AddChild(row);
        }

        if (_selected.Messages.Count == 0)
        {
            MessageList.AddChild(new Label
            {
                Text = Loc.GetString("chitter-log-no-messages"),
                FontColorOverride = Color.Gray,
            });
        }
    }
}
